//! Immutable synthetic input; no new trust, installation or execution claim.
use super::*;

#[test]
fn frozen_fixture_exact_bytes_and_seeded_corruption_remain_bound() {
    assert_eq!(SOURCE_COMMIT, "62114be0f5da3218706e30d7424acfb5d0579d07");
    let bytes = frozen_root_lock();
    assert_eq!(bytes.len(), 175300);
    assert_eq!(ArtifactDigest::of(bytes).sha256, ROOT_LOCK_SHA256);
    assert!(!bytes.contains(&b'\r') && !bytes.starts_with(&[0xef, 0xbb, 0xbf]));
    assert!(bytes.starts_with(b"# This file is automatically @generated by Cargo."));
    assert_eq!(
        ArtifactDigest::of(OBSERVER_LOCK).sha256,
        OBSERVER_LOCK_SHA256
    );
    let fixture = Synthetic::new();
    let verified = fixture.verified();
    verified.verify_contents(&fixture.contents()).unwrap();
    let mut seed = 0x0074_f10c_u64;
    for _ in 0..32 {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        let mut changed = bytes.to_vec();
        changed[seed as usize % bytes.len()] ^= 1;
        let mut contents = fixture.contents();
        contents.root_lock = &changed;
        assert!(matches!(
            verified.verify_contents(&contents),
            Err(ArtifactError::Contents)
        ));
    }
    println!("HC074-FROZEN-LOCK seed=0x074f10c mutations=32 production_pin_changed=false execution=false");
}

#[test]
fn frozen_fixture_moving_workspace_and_resigned_substitution_remain_refused() {
    let current = include_bytes!("../../../../Cargo.lock");
    assert_ne!(ArtifactDigest::of(current).sha256, ROOT_LOCK_SHA256);
    let mut fixture = Synthetic::new();
    let verified = fixture.verified();
    let mut contents = fixture.contents();
    contents.root_lock = current;
    assert!(matches!(
        verified.verify_contents(&contents),
        Err(ArtifactError::Contents)
    ));
    fixture.statement.root_lock = ArtifactDigest::of(current);
    let (raw, identity) = fixture.receipt();
    assert!(matches!(
        verify_receipt(&raw, &identity, &fixture.trust()),
        Err(ArtifactError::Invalid)
    ));
}
